CREATE TABLE departments(
    department_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    department_name VARCHAR2(100) NOT NULL,
    office_location VARCHAR2(100),
    active          BOOLEAN DEFAULT TRUE NOT NULL,
    
    CONSTRAINT pk_departments PRIMARY KEY (department_id),
    CONSTRAINT uq_departments_name UNIQUE (department_name)
);

CREATE TABLE instructors(
    instructor_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    employee_number VARCHAR2(20) NOT NULL,
    first_name      VARCHAR2(50) NOT NULL,
    last_name       VARCHAR2(50) NOT NULL,
    email           VARCHAR2(254),
    department_id   NUMBER NOT NULL,
    hire_date       DATE NOT NULL,
    active          BOOLEAN DEFAULT TRUE NOT NULL,
    
    CONSTRAINT pk_instructors PRIMARY KEY (instructor_id),
    CONSTRAINT uq_instructors_empno UNIQUE (employee_number),
    CONSTRAINT uq_instructors_email UNIQUE (email),
    CONSTRAINT fk_instructors_dept FOREIGN KEY (department_id) REFERENCES departments (department_id)
);

CREATE TABLE students(
    student_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    student_number    VARCHAR2(20) NOT NULL,
    first_name        VARCHAR2(50) NOT NULL,
    last_name         VARCHAR2(50) NOT NULL,
    date_of_birth     DATE NOT NULL,
    email             VARCHAR2(254),
    enrollment_status VARCHAR2(15) DEFAULT 'ACTIVE' NOT NULL,
    created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    
    CONSTRAINT pk_students PRIMARY KEY (student_id),
    CONSTRAINT uq_students_number UNIQUE (student_number),
    CONSTRAINT uq_students_email UNIQUE (email),
    CONSTRAINT ck_students_status CHECK (enrollment_status IN ('ACTIVE', 'INACTIVE', 'GRADUATED', 'WITHDRAWN'))
);

CREATE TABLE academic_terms(
    term_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    term_name   VARCHAR2(50) NOT NULL,
    start_date  DATE NOT NULL,
    end_date    DATE NOT NULL,
    term_status VARCHAR2(10) DEFAULT 'PLANNED' NOT NULL,
    
    CONSTRAINT pk_academic_terms PRIMARY KEY (term_id),
    CONSTRAINT uq_academic_terms_name UNIQUE (term_name),
    CONSTRAINT ck_academic_terms_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_academic_terms_status CHECK (term_status IN ('PLANNED', 'ACTIVE', 'CLOSED'))
);

CREATE TABLE courses(
    course_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    course_code     VARCHAR2(20) NOT NULL,
    course_name     VARCHAR2(100) NOT NULL,
    department_id   NUMBER NOT NULL,
    credits         NUMBER(3,1) NOT NULL,
    active          BOOLEAN DEFAULT TRUE NOT NULL,
    
    CONSTRAINT pk_courses PRIMARY KEY (course_id),
    CONSTRAINT uq_courses_code UNIQUE (course_code),
    CONSTRAINT fk_courses_dept FOREIGN KEY (department_id) REFERENCES departments (department_id),
    CONSTRAINT ck_courses_credits CHECK (credits BETWEEN 0.5 AND 10)
);

CREATE TABLE application_users(
    app_user_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR2(50) NOT NULL,
    display_name VARCHAR2(100) NOT NULL,
    staff_role VARCHAR2(20) NOT NULL,
    instructor_id NUMBER,
    active BOOLEAN DEFAULT TRUE NOT NULL,
    
    CONSTRAINT pk_app_users PRIMARY KEY (app_user_id),
    CONSTRAINT uq_app_users_name UNIQUE (username),
    CONSTRAINT uq_app_users_instructor UNIQUE (instructor_id),
    CONSTRAINT fk_app_users_instructor FOREIGN KEY (instructor_id) REFERENCES instructors (instructor_id),
    CONSTRAINT ck_app_users_role CHECK (staff_role IN ('ADMIN', 'REGISTRAR', 'INSTRUCTOR', 'COUNSELOR'))
);

CREATE TABLE course_sections(
    section_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    course_id       NUMBER NOT NULL,
    term_id         NUMBER NOT NULL,
    instructor_id   NUMBER,
    section_number  VARCHAR2(10) NOT NULL,
    room_number     VARCHAR2(30), --probably doesnt need its own table but eventually maybe,
    capacity        NUMBER(3) DEFAULT 25 NOT NULL,
    
    CONSTRAINT pk_course_sections PRIMARY KEY (section_id),
    CONSTRAINT uq_course_sections UNIQUE (course_id, term_id, section_number),
    CONSTRAINT fk_sections_course FOREIGN KEY (course_id) REFERENCES courses (course_id),
    CONSTRAINT fk_sections_term FOREIGN KEY (term_id) REFERENCES academic_terms (term_id),
    CONSTRAINT fk_sections_instructor FOREIGN KEY (instructor_id) REFERENCES instructors (instructor_id),
    CONSTRAINT ck_sections_capacity CHECK (capacity BETWEEN 1 AND 200)
);

CREATE TABLE enrollments(
    enrollment_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    student_id          NUMBER NOT NULL,
    section_id          NUMBER NOT NULL,
    enrollment_date     DATE DEFAULT SYSDATE NOT NULL,
    enrollment_status   VARCHAR2(12) DEFAULT 'ENROLLED' NOT NULL,
    final_score         NUMBER(5,2),
    
    CONSTRAINT pk_enrollments PRIMARY KEY (enrollment_id),
    CONSTRAINT uq_enroll_student_section UNIQUE (student_id, section_id),
    CONSTRAINT fk_enrollments_student FOREIGN KEY (student_id) REFERENCES students (student_id),
    CONSTRAINT fk_enrollments_section FOREIGN KEY (section_id) REFERENCES course_sections (section_id),
    CONSTRAINT ck_enrollments_status CHECK (enrollment_status IN ('ENROLLED', 'COMPLETED', 'DROPPED', 'WITHDRAWN')),
    CONSTRAINT ck_enrollments_final_score CHECK (final_score BETWEEN 0 AND 100)
);

CREATE TABLE attendance(
    attendance_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    enrollment_id NUMBER NOT NULL,
    class_date DATE NOT NULL,
    attendance_status VARCHAR2(10) NOT NULL,
    recorded_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    
    CONSTRAINT pk_attendance PRIMARY KEY (attendance_id),
    CONSTRAINT uq_attendance_class_date UNIQUE (enrollment_id, class_date),
    CONSTRAINT fk_attendance_enrollment FOREIGN KEY (enrollment_id) REFERENCES enrollments(enrollment_id),
    CONSTRAINT ck_attendance_status CHECK (attendance_status IN ('PRESENT', 'ABSENT', 'TARDY', 'EXCUSED')),
    CONSTRAINT ck_attendance_date_only CHECK (class_date = TRUNC(class_date))
);

CREATE TABLE grade_history(
    grade_id            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    enrollment_id       NUMBER NOT NULL,
    assessment_name     VARCHAR2(100) NOT NULL,
    assessment_type     VARCHAR2(15) NOT NULL,
    score               NUMBER(5,2) NOT NULL,
    max_score           NUMBER(5,2) NOT NULL,
    recorded_by_user_id NUMBER,
    recorded_at         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    
    CONSTRAINT pk_grade_history PRIMARY KEY (grade_id),
    CONSTRAINT uq_grade_hist_assessment UNIQUE (enrollment_id, assessment_name),
    CONSTRAINT fk_grade_history_enrollment FOREIGN KEY (enrollment_id) REFERENCES enrollments (enrollment_id),
    CONSTRAINT fk_grade_hist_recorded_by_user FOREIGN KEY (recorded_by_user_id) REFERENCES application_users (app_user_id),
    CONSTRAINT ck_grade_history_type CHECK (assessment_type IN ('QUIZ', 'TEST', 'PROJECT', 'HOMEWORK', 'EXAM', 'OTHER')),
    CONSTRAINT ck_grade_history_score CHECK (score >= 0),
    CONSTRAINT ck_grade_history_max_score CHECK (max_score > 0),
    CONSTRAINT ck_grade_history_score_validate CHECK (score <= max_score)
);